/// Раздел данных, изменение которого обновляет экраны.
enum KvDomain {
  /// Сеанс и учётная запись.
  auth,

  /// Агрегаты и их режим.
  equipment,

  /// Показания.
  telemetry,

  /// Осмотры и диагностика.
  inspections,

  /// Находки.
  findings,

  /// Задания и сообщения о неисправностях.
  workflow,

  /// Уведомления.
  notifications,

  /// План ТО.
  plan,

  /// Отчёты.
  reports,

  /// Ассистент.
  assistant,

  /// Цеховой сервер, источники, модели.
  admin,

  /// Учётные записи, роли, политика, журнал безопасности.
  security,
}

/// Поток изменений данных: после каждого изменения сервер (демонстрационный или настоящий) сообщает раздел.
abstract interface class KvChangeFeed {
  /// Изменённые разделы.
  Stream<KvDomain> get changes;
}
